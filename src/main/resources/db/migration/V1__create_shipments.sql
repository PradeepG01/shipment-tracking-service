CREATE TABLE shipments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number     VARCHAR(20)   NOT NULL UNIQUE,
    sender_name         VARCHAR(255)  NOT NULL,
    recipient_name      VARCHAR(255)  NOT NULL,
    origin_pincode      VARCHAR(6)    NOT NULL,
    destination_pincode VARCHAR(6)    NOT NULL,
    weight_kg           NUMERIC(8, 2) NOT NULL,
    status              VARCHAR(20)   NOT NULL,
    expected_delivery   DATE          NOT NULL,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    version             BIGINT        NOT NULL DEFAULT 0
);

CREATE INDEX idx_shipments_status_created ON shipments (status, created_at);

CREATE TABLE tracking_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id BIGINT       NOT NULL REFERENCES shipments (id) ON DELETE CASCADE,
    status      VARCHAR(20)  NOT NULL,
    location    VARCHAR(255) NOT NULL,
    note        VARCHAR(500),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_tracking_events_shipment ON tracking_events (shipment_id, occurred_at);
